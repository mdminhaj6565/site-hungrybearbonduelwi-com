    function contactUsSubmit(event) {
        event.preventDefault();

        var form = $("#ContactPostForm");
        ShowLoading();
        $.ajax({
            type: "POST",
            url: "/Home/ContactPost",
            data: form.serialize(),
            success: function(data){
                if (data.indexOf('{"message":') != -1) {
                    var jsonData = $.parseJSON(data);
                    if (!jsonData.success) {
                        $("#contactResponseMessage").html('<div id="alert-override" class="alert alert-warning alert-dissmisable" role="alert"><button type="button" class="close" data-dismiss="alert" aria-label="Close"><span aria-hidden="true">&times;</span></button>' + jsonData.message + '</div>');
                    }
                    else{
                        $("#contactResponseMessage").html('<div id="alert-override" class="alert alert-success alert-dissmisable" role="alert"><button type="button" class="close" data-dismiss="alert" aria-label="Close"><span aria-hidden="true">&times;</span></button>' + jsonData.message + '</div>');
                        $("#btnContactPost").prop('disabled', true);
                        $("#btnContactPost").css('font-weight', 'normal');
                    }
                }
            }
        }).always(function() {
            HideLoading();
        });
    }

